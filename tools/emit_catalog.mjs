import fs from "node:fs";
import { parseAgencies, parsePermits, RESIDENTIAL_REQUIRED_DOCUMENTS, sqlLiteral } from "../lib/catalog.ts";

const agencies = parseAgencies(fs.readFileSync("docs/sources/guam-agencies.md", "utf8"));
const permits = parsePermits(fs.readFileSync("docs/sources/guam-permits-catalog.md", "utf8"), agencies);
const payload = { agencies, permits, requiredDocuments: RESIDENTIAL_REQUIRED_DOCUMENTS };
fs.mkdirSync("lib", { recursive: true });
fs.writeFileSync("lib/catalog.generated.json", JSON.stringify(payload, null, 2));

const lines = [];
lines.push("-- Generated by tools/emit_catalog.mjs from docs/sources. Do not edit by hand.");
lines.push("insert into public.agencies (code, name, acronym, website, group_name, notes) values");
lines.push(
  agencies
    .map(
      (agency) =>
        `  (${sqlLiteral(agency.code)}, ${sqlLiteral(agency.name)}, ${sqlLiteral(agency.acronym)}, ${sqlLiteral(agency.website)}, ${sqlLiteral(agency.groupName)}, ${sqlLiteral(agency.notes)})`,
    )
    .join(",\n"),
);
lines.push("on conflict (code) do update set group_name = coalesce(public.agencies.group_name, excluded.group_name), notes = coalesce(public.agencies.notes, excluded.notes);");
lines.push("");
lines.push("insert into public.permit_catalog (code, name, group_name, agency_label, agency_code, source, unverified, trackable, application_type_code) values");
lines.push(
  permits
    .map(
      (permit) =>
        `  (${sqlLiteral(permit.code)}, ${sqlLiteral(permit.name)}, ${sqlLiteral(permit.groupName)}, ${sqlLiteral(permit.agencyLabel)}, ${sqlLiteral(permit.agencyCode)}, ${sqlLiteral(permit.source)}, ${permit.unverified}, ${permit.trackable}, ${permit.trackable ? sqlLiteral("building_permit_residential_one_family") : "null"})`,
    )
    .join(",\n"),
);
lines.push("on conflict (code) do nothing;");
lines.push("");
lines.push("insert into public.required_documents (application_type_id, code, name, required, notes)");
lines.push(
  RESIDENTIAL_REQUIRED_DOCUMENTS.map(
    (document) =>
      `select id, ${sqlLiteral(document.code)}, ${sqlLiteral(document.name)}, ${document.required}, ${sqlLiteral(document.notes)} from public.application_types where code = ${sqlLiteral(document.applicationTypeCode)}`,
  ).join("\nunion all\n"),
);
lines.push("on conflict (application_type_id, code) do nothing;");
fs.writeFileSync("supabase/catalog_seed.sql", lines.join("\n") + "\n");
console.log(`agencies ${agencies.length} permits ${permits.length}`);
